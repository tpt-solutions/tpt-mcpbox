//! `tpt-mcpbox init tool`: scaffold a tool component project.
//!
//! The SDK is not published yet, so the scaffold takes its location explicitly
//! and writes it as a path dependency. A guessed path would scaffold a project
//! that fails to build.

use std::path::{Path, PathBuf};

const CARGO_TOML: &str = r#"# Generated by `tpt-mcpbox init tool`.

[package]
name = "{{package}}"
version = "0.1.0"
edition = "2024"
publish = false

# A tool component is its own workspace, built for wasm32-wasip2.
[workspace]

[lib]
crate-type = ["cdylib"]

[dependencies]
tpt-mcpbox-sdk = { path = "{{sdk}}" }
schemars = "1"
serde = { version = "1", features = ["derive"] }

[profile.release]
opt-level = "s"
"#;

const LIB_RS: &str = r#"// Generated by `tpt-mcpbox init tool`.
//
// Build with:  cargo build --release --target wasm32-wasip2

use schemars::JsonSchema;
use serde::Deserialize;
use tpt_mcpbox_sdk::{Tool, ToolError, ToolResult, export_tools};

#[derive(Deserialize, JsonSchema)]
struct GreetArgs {
    /// Who to greet.
    name: String,
}

struct Greet;

impl Tool for Greet {
    type Args = GreetArgs;
    const NAME: &'static str = "greet";
    const DESCRIPTION: &'static str = "Greets someone by name";

    fn run(args: GreetArgs) -> Result<ToolResult, ToolError> {
        Ok(ToolResult::text(format!("Hello, {}!", args.name)))
    }
}

export_tools!(Greet);
"#;

const GITIGNORE: &str = "/target\n";

/// Starter configuration: no tools, deny by default, audit on. A new hub
/// refuses every call until the operator adds a tool and a rule for it.
const CONFIG_YAML: &str = r#"# Generated by `tpt-mcpbox init`. See examples/tpt-mcpbox.yaml for a
# configuration with tools, secrets and policy rules filled in.

version: 1

server:
  transports: [stdio]

# Add tools here, for example:
#
# tools:
#   - name: read_notes
#     wasm_path: tools/read_notes.wasm
#     capabilities:
#       filesystem:
#         read: ["./workspace/**"]
#       memory_limit: "64MB"
#       time_limit: "10s"

policy:
  # Anything not allowed by a rule below is refused.
  default: deny
  rules: []

audit:
  enabled: true
  path: .mcpbox/audit.log
"#;

/// Writes a starter configuration to `path`.
///
/// An existing file is left alone unless `force` is set, since overwriting an
/// operator's configuration is not something a scaffold should do silently.
///
/// # Errors
///
/// Returns a message if the file exists and `force` is false, or it cannot be
/// written.
pub(crate) fn scaffold_config(path: &Path, force: bool) -> Result<PathBuf, String> {
    if path.exists() && !force {
        return Err(format!(
            "{} already exists; pass --force to overwrite it",
            path.display()
        ));
    }
    std::fs::write(path, CONFIG_YAML)
        .map_err(|error| format!("cannot write {}: {error}", path.display()))?;
    Ok(path.to_path_buf())
}

/// Writes a new tool project into `dir`.
///
/// # Errors
///
/// Returns a message if `dir` exists and is not empty, or a file cannot be
/// written.
pub(crate) fn scaffold_tool(dir: &Path, sdk: &Path) -> Result<Vec<PathBuf>, String> {
    if dir.exists()
        && dir
            .read_dir()
            .map_or(true, |mut entries| entries.next().is_some())
    {
        return Err(format!("{} already exists and is not empty", dir.display()));
    }
    let name = package_name(dir)?;
    let sdk = sdk.display().to_string().replace('\\', "/");

    let files = [
        (
            "Cargo.toml",
            CARGO_TOML
                .replace("{{package}}", &name)
                .replace("{{sdk}}", &sdk),
        ),
        ("src/lib.rs", LIB_RS.to_owned()),
        (".gitignore", GITIGNORE.to_owned()),
    ];

    let mut written = Vec::new();
    for (relative, contents) in files {
        let path = dir.join(relative);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|error| format!("cannot create {}: {error}", parent.display()))?;
        }
        std::fs::write(&path, contents)
            .map_err(|error| format!("cannot write {}: {error}", path.display()))?;
        written.push(path);
    }
    Ok(written)
}

/// Cargo package name derived from the directory name: lowercase letters,
/// digits, `-` and `_`, starting with a letter.
fn package_name(dir: &Path) -> Result<String, String> {
    let raw = dir
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or_else(|| format!("{} has no usable name", dir.display()))?;
    let mut name: String = raw
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect();
    if !name.starts_with(|c: char| c.is_ascii_alphabetic()) {
        name.insert_str(0, "tool-");
    }
    Ok(name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scaffold_writes_a_project_with_the_sdk_path() {
        let root = tempfile::tempdir().unwrap();
        let dir = root.path().join("My Tool");
        let written = scaffold_tool(&dir, Path::new(r"C:\src\tpt-mcpbox-sdk")).unwrap();
        assert_eq!(written.len(), 3);

        let manifest = std::fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        assert!(manifest.contains("name = \"my-tool\""), "{manifest}");
        assert!(
            manifest.contains("path = \"C:/src/tpt-mcpbox-sdk\""),
            "{manifest}"
        );
        assert!(
            std::fs::read_to_string(dir.join("src/lib.rs"))
                .unwrap()
                .contains("export_tools!(Greet);")
        );
    }

    #[test]
    fn scaffold_refuses_a_non_empty_directory() {
        let root = tempfile::tempdir().unwrap();
        std::fs::write(root.path().join("keep.txt"), "x").unwrap();
        assert!(scaffold_tool(root.path(), Path::new("/sdk")).is_err());
    }

    #[test]
    fn scaffold_config_writes_a_configuration_that_passes_serve_validation() {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join("tpt-mcpbox.yaml");
        scaffold_config(&path, false).unwrap();

        let loaded = tpt_mcpbox_config::load::load_file(&path).expect("scaffold loads");
        let report = tpt_mcpbox_config::validate::validate(
            &loaded.config,
            tpt_mcpbox_config::validate::ValidationMode::Serve,
        );
        assert!(report.is_ok(), "{report}");
    }

    #[test]
    fn scaffold_config_refuses_to_overwrite_without_force() {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join("tpt-mcpbox.yaml");
        std::fs::write(&path, "keep me").unwrap();

        assert!(scaffold_config(&path, false).is_err());
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "keep me");

        scaffold_config(&path, true).unwrap();
        assert!(
            std::fs::read_to_string(&path)
                .unwrap()
                .contains("default: deny")
        );
    }

    #[test]
    fn package_names_are_valid_cargo_names() {
        assert_eq!(
            package_name(Path::new("/x/Hello World")).unwrap(),
            "hello-world"
        );
        assert_eq!(package_name(Path::new("/x/9lives")).unwrap(), "tool-9lives");
    }
}
